assert.equal(at('dart_a',600,660,[],[{resource:'venue',blocksAll:true,date:d,start:600,end:840}]).ok,false);
assert.equal(at('dart_a',600,660,[],[{resource:'venue',scope:'venue_only',date:d,start:600,end:840}]).ok,true);
assert.equal(at('venue',600,840,[],[{resource:'venue',scope:'venue_only',date:d,start:600,end:840}]).kind,'blocked');
assert.equal(at('hyzr',660,690,[{resource:'hyzr',date:d,start:660,end:720,status:'cancelled'}]).ok,true);
assert.equal(at('hyzr',660,690,[{resource:'hyzr',date:d,start:660,end:720,status:'held',holdUntil:'2026-11-05T10:00:00Z'}]).ok,true);
assert.equal(at('hyzr',660,690,[{resource:'hyzr',date:d,start:660,end:720,status:'pending_payment'}]).ok,false);
assert.equal(at('hyzr',600,615,[]).ok,false);
assert.equal(at('venue',600,660,[]).ok,false);
assert.equal(slotsForDay({resource:'hyzr',date:d,from:600,to:720,duration:30,reservations:confirmed}).length,4);
assert.equal(demoQuote('hyzr',90,{hyzr:79,dart_a:59,dart_b:59,venueBase:799,venueExtraHalf:109}),237);
