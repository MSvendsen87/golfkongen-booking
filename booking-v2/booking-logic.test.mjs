import assert from 'node:assert/strict';
import {timeToMinutes,minutesToTime,resourcesFor,overlaps,availability,slotsForDay,demoQuote,appliesOnDate} from './booking-logic.mjs';
const d='2026-11-05';
const confirmed=[{id:'b1',resource:'hyzr',date:d,start:660,end:720,status:'confirmed'}];
const at=(resource,start,end,bookings=confirmed,blocks=[])=>availability({resource,date:d,start,end,reservations:bookings,blocks,nowEpochMs:Date.parse('2026-11-06T00:00:00Z')});
assert.equal(timeToMinutes('12:30'),750);
assert.equal(appliesOnDate({dateFrom:'2026-10-19',dateTo:'2026-10-31'},'2026-10-24'),true);
assert.equal(appliesOnDate({dateFrom:'2026-10-19',dateTo:'2026-10-31'},'2026-11-01'),false);
assert.equal(appliesOnDate({dateFrom:'2026-05-30',dateTo:'2026-12-19',weekdays:[6]},'2026-11-07'),true);
assert.equal(appliesOnDate({dateFrom:'2026-05-30',dateTo:'2026-12-19',weekdays:[6]},'2026-11-05'),false);
assert.equal(minutesToTime(750),'12:30');
assert.throws(()=>timeToMinutes('25:50'));
assert.deepEqual(resourcesFor('venue'),['hyzr','dart_a','dart_b']);
assert.equal(overlaps(600,660,660,720),false);
assert.equal(overlaps(600,661,660,720),true);
assert.equal(at('hyzr',660,690).ok,false);
assert.equal(at('hyzr',630,660).ok,true);
assert.equal(at('dart_a',660,720).ok,true);
assert.equal(at('venue',630,870).ok,false);
assert.equal(at('venue',720,960).ok,true);
assert.equal(at('hyzr',600,660,[],[{resource:'hyzr',date:d,start:600,end:660,label:'Service'}]).kind,'blocked');
